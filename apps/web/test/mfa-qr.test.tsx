const flatten = (modules: readonly (readonly boolean[])[]): string =>
  modules.map((row) => row.map((dark) => (dark ? '1' : '0')).join('')).join('');

describe('QR encoder — parity with a reference implementation', () => {
  for (const fixture of FIXTURES) {
    it(`matches version ${fixture.version} module for module`, () => {
      const symbol = encodeQr(fixture.text);
      expect(symbol).not.toBeNull();
      expect(symbol?.version).toBe(fixture.version);
      expect(symbol?.size).toBe(fixture.size);
      // The mask is chosen by the spec's penalty rules, so agreeing on it is
      // itself evidence the whole symbol was scored identically.
      expect(symbol?.mask).toBe(fixture.mask);
      expect(flatten(symbol?.modules ?? [])).toBe(fixture.modules);
    });
  }

  it('places the three finder patterns every scanner looks for first', () => {
    const symbol = encodeQr(FIXTURES[1]?.text ?? '');
    const size = symbol?.size ?? 0;
    const at = (r: number, c: number) => symbol?.modules[r]?.[c];

    const corners: readonly (readonly [number, number])[] = [
      [0, 0],
      [0, size - 7],
      [size - 7, 0],
    ];
    for (const [r0, c0] of corners) {
      expect(at(r0, c0)).toBe(true); // outer ring
      expect(at(r0 + 1, c0 + 1)).toBe(false); // light gap
      expect(at(r0 + 3, c0 + 3)).toBe(true); // 3×3 core
    }
    // The module at (4·version + 9, 8) is dark in every valid symbol.
    expect(at(size - 8, 8)).toBe(true);
  });

  it('refuses to emit a symbol it cannot encode, rather than a wrong one', () => {
    expect(byteCapacity(10)).toBe(213);
    expect(encodeQr('x'.repeat(213))).not.toBeNull();
    expect(encodeQr('x'.repeat(214))).toBeNull();
  });

  it('grows the version with the payload instead of overflowing', () => {
    expect(encodeQr('x'.repeat(14))?.version).toBe(1);
    expect(encodeQr('x'.repeat(15))?.version).toBe(2);
    expect(encodeQr('x'.repeat(106))?.version).toBe(6);
  });

  it('renders every dark module into the SVG path', () => {
    const symbol = encodeQr('a');
    const darkCount = (symbol?.modules ?? []).flat().filter(Boolean).length;
    const path = modulesToPath(symbol?.modules ?? []);
    expect(path.match(/M/g)).toHaveLength(darkCount);
    expect(path.startsWith('M0 0h1v1h-1z')).toBe(true);
  });

  it('handles non-ASCII by encoding UTF-8 bytes, not code units', () => {
    // A label can contain anything; two-byte characters must count as two.
    expect(encodeQr('é'.repeat(7))?.version).toBe(1); // 14 bytes — exactly full
    expect(encodeQr('é'.repeat(8))?.version).toBe(2);
  });
});
